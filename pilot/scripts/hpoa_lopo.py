OUT = Path("pilot/cache/v3/p0/hpoa_lopo")
HPOA = Path(CA.HPOA)
SMIX = Path("pilot/cache/v2/devD/variants/dev_v3llmd_ns_ot0.5.json")
STORED_BASE = Path("pilot/cache/v2/devD/ref_hpoa/dev.json")
PP_ZIP = O.DATA / "external_benchmarks/phenopacket_store/all_phenopackets.zip"
VARIANTS = ("base", "lopo", "rand_s0", "rand_s1", "rand_s2", "rand_dz_s0", "lopo_strip", "nopmid", "rand_nopmid")
FOLDS = 10
FOLD_VARIANTS = tuple(f"lopo_f{k}" for k in range(FOLDS))
PP = "Phenopacket-store"
COMMON = ["DDXPlus-test", "SymCat"]
RARE = ["PUMCH-ADM", "PUMCH_L", "Phenopacket-store", "RareBench-HMS", "RareBench-LIRICAL",
        "RareBench-MME", "RareBench-RAMEDIS"]
GROUPS = {"rare (7 sets)": RARE, "common (DDXPlus, SymCat)": COMMON, "all nine": COMMON + RARE}


def evaluated_cases() -> list[tuple[tuple[set[str], set[str]], set[str]]]:
    """Phenopacket-store cases graph_dx.py evaluates (gold key and evidence present), in its order, with the
    PMIDs in each file name and externalReferences."""
    O.RAW_GOLD = True
    pats = O.load_phenopacket()[PP]
    z = zipfile.ZipFile(PP_ZIP)
    names = sorted(n for n in z.namelist() if n.endswith(".json"))
    if len(names) != len(pats):
        raise SystemExit(f"loader order check failed: {len(names)} files, {len(pats)} cases")
    out = []
    for name, (gold, ev) in zip(names, pats):
        if not (v2_ids.gold_keys(gold) and ev):
            continue
        meta = json.loads(z.read(name)).get("metaData", {}).get("externalReferences", [])
        pm = set(re.findall(r"PMID_(\d+)", name.rsplit("/", 1)[-1]))
        pm |= {r["id"][5:] for r in meta if r.get("id", "").startswith("PMID:")}
        out.append(((gold, ev), {f"PMID:{p}" for p in pm}))
    return out


def fold_split(case_pm: list[set[str]]) -> list[int]:
    """Fold per case; cases linked by a shared PMID form one group and stay in one fold."""
    root = list(range(len(case_pm)))

    def find(i: int) -> int:
        while root[i] != i:
            root[i] = root[root[i]]
            i = root[i]
        return i

    first: dict[str, int] = {}
    for i, pm in enumerate(case_pm):
        for p in sorted(pm):
            if p in first:
                root[find(i)] = find(first[p])
            else:
                first[p] = i
    groups: dict[int, list[int]] = defaultdict(list)
    for i in range(len(case_pm)):
        groups[find(i)].append(i)
    order = sorted(groups)
    random.Random(0).shuffle(order)
    size, fold = [0] * FOLDS, [0] * len(case_pm)
    for g in order:
        k = min(range(FOLDS), key=lambda f: (size[f], f))
        for i in groups[g]:
            fold[i] = k
        size[k] += len(groups[g])
    return fold


def read_rows() -> tuple[list[str], dict[int, tuple[str, list[str]]]]:
    """All lines, and for the rows the build reads: line index -> (database_id, references)."""
    lines = HPOA.read_text().splitlines(keepends=True)
    rows = {}
    for i, ln in enumerate(lines):
        if ln.startswith(("#", "database_id")):
            continue
        f = ln.rstrip("\n").split("\t")
        if f[2] != "NOT" and f[10] == "P":
            rows[i] = (f[0], [r.strip() for r in f[4].split(";") if r.strip()])
    return lines, rows


def deletions(rows: dict[int, tuple[str, list[str]]], case_pm: list[set[str]],
              fold: list[int]) -> tuple[dict[str, set[int]], dict]:
    held = set().union(*case_pm)
    idx = sorted(rows)
    lopo = {i for i in idx if held & set(rows[i][1])}
    out: dict[str, set[int]] = {
        "base": set(), "lopo": lopo,
        "lopo_strip": {i for i in lopo if set(rows[i][1]) <= held},
        "nopmid": {i for i in idx if any(r.startswith("PMID:") for r in rows[i][1])}}
    for s in (0, 1, 2):
        out[f"rand_s{s}"] = set(random.Random(s).sample(idx, len(lopo)))
    out["rand_nopmid"] = set(random.Random(0).sample(idx, len(out["nopmid"])))
    by_dz, cut = defaultdict(list), defaultdict(int)
    for i in idx:
        if i in lopo:
            cut[rows[i][0]] += 1
        else:
            by_dz[rows[i][0]].append(i)
    rng, matched, short = random.Random(0), set(), 0
    for d in sorted(cut):
        k = min(cut[d], len(by_dz[d]))
        short += cut[d] - k
        matched |= set(rng.sample(by_dz[d], k))
    out["rand_dz_s0"] = matched
    for k in range(FOLDS):
        held_k = set().union(*(pm for pm, f in zip(case_pm, fold) if f == k))
        out[f"lopo_f{k}"] = {i for i in lopo if held_k & set(rows[i][1])}
    return out, {"held_out_pmids": len(held), "rows_citing_a_held_out_pmid": len(lopo),
                 "rand_dz_s0_shortfall_rows": short, "lopo_diseases": len(cut)}


def edges(path: Path, uni: dict, h2c, par) -> dict[str, set[str]]:
    """Universe disease -> concept profile exactly as build_reference_graph.pairs_hpoa builds it."""
    CA.HPOA = str(path)
    exact, _ = CA.curated_pairs(h2c, par)
    return {d: cs for d, cs in exact.items() if d in uni and cs}


def prepare(hpoa_dir: Path) -> None:
    case_pm = [pm for _, pm in evaluated_cases()]
    fold = fold_split(case_pm)
    lines, rows = read_rows()
    dels, extra = deletions(rows, case_pm, fold)
    uni = dict(v2_ids.universe())
    for k in json.loads(Path("pilot/cache/v2/exclude_nonhuman_diseases.json").read_text()):
        uni.pop(k, None)
    h2c, par = CA.hpo_to_cui()
    clusters = gold_clusters()
    hpoa_dir.mkdir(parents=True, exist_ok=True)
    base_prof: dict[str, set[str]] = {}
    if len(clusters[PP]) != len(case_pm):
        raise SystemExit(f"{PP}: {len(clusters[PP])} clustered cases, {len(case_pm)} with PMIDs")
    info = {"hpoa": str(HPOA), "hpoa_sha256": hashlib.sha256(HPOA.read_bytes()).hexdigest(),
            "phenopacket_cases_evaluated": len(case_pm), "rows_read_by_build": len(rows), **extra,
            "folds": {"cases": [fold.count(k) for k in range(FOLDS)],
                      "pmids": [len(set().union(*(pm for pm, f in zip(case_pm, fold) if f == k)))
                                for k in range(FOLDS)],
                      "fold": "".join(map(str, fold))},
            "variants": {}}
    fold_status = [""] * len(case_pm)
    for v in VARIANTS + FOLD_VARIANTS:
        path = hpoa_dir / f"{v}.hpoa"
        text = "".join(ln for i, ln in enumerate(lines) if i not in dels[v])
        path.write_text(text)
        prof = edges(path, uni, h2c, par)
        if v == "base":
            base_prof = prof
        lost = {d: base_prof[d] - prof.get(d, set()) for d in base_prof}
        lost = {d: c for d, c in lost.items() if c}
        emptied = {d for d in base_prof if d not in prof}
        per_set = {}
        for b, keys in clusters.items():
            hit = [any(g in lost for g in ks) for ks in keys]
            had = [[g for g in ks if g in base_prof] for ks in keys]
            gone = [bool(h) and all(g in emptied for g in h) for h in had]
            per_set[b] = {"patients": len(keys), "gold_lost_edges_pct": round(100 * sum(hit) / len(keys), 1),
                          "gold_profile_emptied_pct": round(100 * sum(gone) / len(keys), 1)}
            # per patient, in ranking order: 0 gold profile intact, 1 lost edges, 2 emptied
            status = ["2" if g else "1" if h else "0" for h, g in zip(hit, gone)]
            if v == "lopo":
                per_set[b]["status"] = "".join(status)
            if v in FOLD_VARIANTS and b == PP:
                for i, f in enumerate(fold):
                    if v == f"lopo_f{f}":
                        fold_status[i] = status[i]
        info["variants"][v] = {
            "rows_removed": len(dels[v]), "edges": sum(len(c) for c in prof.values()),
            "edges_lost": sum(len(c) for c in lost.values()), "diseases_with_findings": len(prof),
            "diseases_losing_edges": len(lost), "diseases_emptied": len(emptied),
            "sha256": hashlib.sha256(text.encode()).hexdigest(), "per_set": per_set}
        print(f"{v:12s} rows -{len(dels[v]):6d}  edges {info['variants'][v]['edges']:7d} "
              f"(-{info['variants'][v]['edges_lost']:6d})  diseases {len(prof):5d} "
              f"(losing {len(lost)}, emptied {len(emptied)})", flush=True)
    info["folds"]["status"] = "".join(fold_status)
    OUT.mkdir(parents=True, exist_ok=True)
    tmp = OUT / "deletions.json.tmp"
    tmp.write_text(json.dumps(info, indent=1))
    tmp.replace(OUT / "deletions.json")


def paired(runs: dict[str, dict], pairs: list[tuple[str, str]], clusters: dict[str, list]) -> tuple[list, list]:
    rows, macros = [], []
    for a, b in pairs:
        for k in (10, 1):
            for r in compare(runs[a], runs[b], k, clusters=clusters, require=COMMON + RARE):
                rows.append({"comparison": f"{b} - {a}", "k": k, "bench": r["bench"], "n": r["n"],
                             "A_pct": r[f"A@{k}"], "B_pct": r[f"B@{k}"], "diff": r["diff"], "ci": r["ci"],
                             "ci_cluster": r.get("ci_cluster"), "diseases": r.get("clusters"),
                             "only_A": r["only_A"], "only_B": r["only_B"], "p_holm": r["p_holm"]})
            for g, gs in GROUPS.items():
                m = macro_compare(runs[a], runs[b], k, gs)
                macros.append({"comparison": f"{b} - {a}", "k": k, "group": g, "A": m["A"], "B": m["B"],
                               "diff": m["diff"], "ci_patient_stratified": m["ci"], "p_bootstrap": m["p"]})
    return rows, macros


def subset(run: dict, bench: str, idx: list[int], n: int) -> dict:
    rk = next(r["ranks_lineage"] for r in run["results"] if r["bench"] == bench)
    if len(rk) != n:
        raise SystemExit(f"{bench}: {len(rk)} ranks, {n} LOPO statuses")
    return {"results": [{"bench": bench, "ranks_lineage": [rk[i] for i in idx]}]}


def subgroups(runs: dict[str, dict], clusters: dict[str, list], status: dict[str, str], scheme: str) -> list[dict]:
    """HPOA graphs - S-mix within the patients whose gold profile the deletion left intact, thinned or emptied."""
    names = {"0": "gold profile intact", "1": "gold lost edges", "2": "gold profile emptied"}
    out = []
    for bench, st in status.items():
        for code, label in names.items():
            idx = [i for i, c in enumerate(st) if c == code]
            if not idx:
                continue
            cl = {bench: [clusters[bench][i] for i in idx]}
            smix = subset(runs["S-mix"], bench, idx, len(st))
            for v in [x for x in runs if x != "S-mix"]:
                for k in (10, 1):
                    r = compare(smix, subset(runs[v], bench, idx, len(st)), k, clusters=cl)[0]
                    out.append({"scheme": scheme, "bench": bench, "group": label, "n": len(idx),
                                "comparison": f"{v} - S-mix",
                                "k": k, "S-mix": r[f"A@{k}"], "HPOA": r[f"B@{k}"], "diff": r["diff"],
                                "ci": r["ci"], "ci_cluster": r.get("ci_cluster"), "diseases": r.get("clusters")})
    return out


def frozen_hpoa() -> dict:
    return json.loads(Path("pilot/cache/v2/devD/frozen_config_D.json").read_text())["comparators"]["hpoa"]["onehop"]


def rank_fold(k: int, uri: str, auth: str, check: Path | None) -> None:
    """Rank fold k's Phenopacket-store cases on the graph loaded at uri with graph_dx.evaluate. With check, the
    loaded graph is lopo and the ranks must equal those graph_dx.py stored for the same cases in check."""
    import graph_dx

    fold = json.loads((OUT / "deletions.json").read_text())["folds"]["fold"]
    cases = [c for c, _ in evaluated_cases()]
    if len(fold) != len(cases):
        raise SystemExit(f"{len(fold)} fold labels, {len(cases)} cases")
    idx = [i for i, f in enumerate(fold) if int(f) == k]
    c = frozen_hpoa()
    dx = graph_dx.GraphDx(uri, auth, c["alpha"], c["mu"], c["decay"], c["unified_w"], c["support_beta"],
                          c["offtopic_w"])
    res = graph_dx.evaluate(dx, PP, [cases[i] for i in idx])
    if res["evaluated"] != len(idx):
        raise SystemExit(f"fold {k}: {res['evaluated']} of {len(idx)} cases evaluated")
    out = {"fold": k, "graph": "lopo" if check else f"lopo_f{k}", "config": c, "indices": idx,
           "ranks_lineage": res["ranks_lineage"], "lineage@10": res["lineage@10"], "lineage@1": res["lineage@1"]}
    if check:
        ref = next(r["ranks_lineage"] for r in json.loads(check.read_text())["results"] if r["bench"] == PP)
        bad = sum(ref[i] != p for i, p in zip(idx, res["ranks_lineage"]))
        if bad:
            raise SystemExit(f"fold ranking differs from {check} for {bad} of {len(idx)} cases")
        out["check"] = f"equal to {check} for all {len(idx)} cases"
        print(out["check"], flush=True)
    path = OUT / ("fold_check.json" if check else f"fold_{k}.json")
    path.write_text(json.dumps(out, indent=1))


def fold_run(lopo: dict) -> dict | None:
    """The lopo run with the Phenopacket-store ranks of the 10-fold scheme, or None until every fold is ranked."""
    files = [OUT / f"fold_{k}.json" for k in range(FOLDS)]
    if not all(f.exists() for f in files):
        return None
    pp = next(r for r in lopo["results"] if r["bench"] == PP)
    ranks: list[int | None | str] = ["missing"] * len(pp["ranks_lineage"])
    for f in files:
        d = json.loads(f.read_text())
        for i, p in zip(d["indices"], d["ranks_lineage"]):
            if ranks[i] != "missing":
                raise SystemExit(f"case {i} ranked twice")
            ranks[i] = p
    if "missing" in ranks:
        raise SystemExit("a Phenopacket-store case has no fold rank")
    n = len(ranks)
    res = [dict(r) for r in lopo["results"]]
    for r in res:
        if r["bench"] == PP:
            r["ranks_lineage"] = ranks
            for kk in O.KS:
                r[f"lineage@{kk}"] = round(100 * sum(p is not None and p <= kk for p in ranks) / n, 2)
    return {"results": res}


def stats() -> None:
    runs = {"S-mix": json.loads(SMIX.read_text())}
    for v in VARIANTS:
        p = OUT / f"dev_{v}.json"
        if p.exists():
            runs[f"HPOA-{v}"] = json.loads(p.read_text())
    if "HPOA-base" not in runs or "HPOA-lopo" not in runs:
        raise SystemExit("dev_base.json and dev_lopo.json are needed; run run_hpoa_lopo.sh")
    stored = {r["bench"]: r["ranks_lineage"] for r in json.loads(STORED_BASE.read_text())["results"]}
    rebuilt = {r["bench"]: r["ranks_lineage"] for r in runs["HPOA-base"]["results"]}
    repro = {b: sum(x != y for x, y in zip(stored[b], rebuilt[b])) if len(stored[b]) == len(rebuilt[b]) else None
             for b in stored}
    if any(v != 0 for v in repro.values()):
        raise SystemExit(f"rebuilt HPOA graph does not reproduce {STORED_BASE}: {repro}")
    clusters = gold_clusters()
    hpoa = [v for v in runs if v != "S-mix"]
    # every HPOA graph against S-mix; the deletion effects only for the main LOPO graphs and the main control
    pairs = [("S-mix", v) for v in hpoa]
    pairs += [("HPOA-base", v) for v in ("HPOA-lopo", "HPOA-rand_s0") if v in runs]
    pairs += [("HPOA-rand_s0", "HPOA-lopo")] if "HPOA-rand_s0" in runs else []
    lopo10 = fold_run(runs["HPOA-lopo"])
    if lopo10:
        runs["HPOA-lopo10"] = lopo10
        hpoa.append("HPOA-lopo10")
        pairs += [("S-mix", "HPOA-lopo10"), ("HPOA-base", "HPOA-lopo10"), ("HPOA-lopo10", "HPOA-lopo"),
                  ("HPOA-rand_s0", "HPOA-lopo10")]
    rows, macros = paired(runs, pairs, clusters)
    dele = json.loads((OUT / "deletions.json").read_text())
    st_all = {b: dele["variants"]["lopo"]["per_set"][b]["status"] for b in (PP, "RareBench-LIRICAL")}
    subs = subgroups(runs, clusters, st_all, "lopo (all case papers)")
    if lopo10:
        subs += subgroups({v: runs[v] for v in ("S-mix", "HPOA-base", "HPOA-rand_s0", "HPOA-lopo10")}, clusters,
                          {PP: dele["folds"]["status"]}, "lopo10 (own fold's papers)")
    res = {"note": "diff = B - A in percentage points of lineage Top-k; ci = patient-paired bootstrap 95% "
                   "(2,000, seed 0); ci_cluster = gold-disease cluster bootstrap 95%; p_holm = exact McNemar, "
                   "Holm across the nine sets of one comparison at one k; macro = equal-weight mean of per-set "
                   "differences, set-stratified patient bootstrap. Development sets: every value is post hoc.",
           "reproduction_mismatched_patients": repro,
           "runs": {"S-mix": str(SMIX), **{v: str(OUT / f"dev_{v[5:]}.json") for v in hpoa if v != "HPOA-lopo10"},
                    **({"HPOA-lopo10": f"dev_lopo.json with {PP} from fold_0..{FOLDS - 1}.json"} if lopo10 else {})},
           "per_set": {v: {r["bench"]: [r["lineage@10"], r["lineage@1"]] for r in runs[v]["results"]} for v in runs},
           "rows": rows, "macro": macros, "lopo_subgroups": subs}
    (OUT / "stats.json").write_text(json.dumps(res, indent=1))
    print("reproduction of the stored HPOA ranks: all patients equal")
    print(f"\n{'comparison':30s} {'k':>3s} {'set':19s} {'n':>6s} {'A':>6s} {'B':>6s} {'diff':>6s} "
          f"{'patient CI':>16s} {'disease CI':>16s} {'Holm p':>8s}")
    shown = {"HPOA-base - S-mix", "HPOA-lopo - S-mix", "HPOA-rand_s0 - S-mix", "HPOA-lopo - HPOA-base",
             "HPOA-lopo - HPOA-rand_s0", "HPOA-lopo10 - S-mix"}
    for r in (r for r in rows if r["comparison"] in shown):
        cc = r["ci_cluster"] or [float("nan")] * 2
        print(f"{r['comparison']:30s} @{r['k']:<2d} {r['bench']:19s} {r['n']:6d} {r['A_pct']:6.2f} {r['B_pct']:6.2f} "
              f"{r['diff']:+6.2f} [{r['ci'][0]:+6.2f},{r['ci'][1]:+6.2f}] [{cc[0]:+6.2f},{cc[1]:+6.2f}] "
              f"{r['p_holm']:8.2g}")
    print("\nmacro (equal-weight over sets, set-stratified patient bootstrap):")
    for m in macros:
        print(f"  {m['comparison']:30s} @{m['k']:<2d} {m['group']:25s} A {m['A']:6.2f} B {m['B']:6.2f} "
              f"{m['diff']:+6.2f} [{m['ci_patient_stratified'][0]:+6.2f},{m['ci_patient_stratified'][1]:+6.2f}]")
    print("\nLOPO subgroups (patients by what lopo removed from their gold disease profile):")
    for r in (r for r in subs if r["k"] == 10):
        print(f"  {r['scheme'][:6]:6s} {r['bench']:19s} {r['group']:21s} n {r['n']:5d} {r['comparison']:24s} "
              f"S-mix {r['S-mix']:6.2f} HPOA {r['HPOA']:6.2f} {r['diff']:+6.2f} [{r['ci'][0]:+6.2f},{r['ci'][1]:+6.2f}]")
    print(f"\nsaved {OUT / 'stats.json'}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["prepare", "rank-fold", "stats"])
    ap.add_argument("--hpoa-dir", type=Path, help="prepare: where the filtered phenotype.hpoa files go")
    ap.add_argument("--fold", type=int, help="rank-fold: fold index")
    ap.add_argument("--check", type=Path, help="rank-fold: graph_dx.py output on the lopo graph to match")
    ap.add_argument("--uri", default="bolt://localhost:7688")
    ap.add_argument("--auth", default=os.environ.get("NEO4J_AUTH", "neo4j/thesis-dev-only"))
    a = ap.parse_args()
    if a.step == "prepare":
        if a.hpoa_dir is None:
            ap.error("prepare needs --hpoa-dir")
        prepare(a.hpoa_dir)
    elif a.step == "rank-fold":
        if a.fold is None:
            ap.error("rank-fold needs --fold")
        rank_fold(a.fold, a.uri, a.auth, a.check)
    else:
        stats()


if __name__ == "__main__":
    main()
