"""HPOA leave-one-publication-out against S-mix on the development sets (research design §9.32 P0-4).

Phenopacket-store cases and many HPOA annotations are curated from the same published case reports, so
the HPOA comparator may score a case with annotations taken from that case's own paper. S-mix never
reads those papers (exclude_pmids_phenopacket.json drops them at collection).

One graph cannot leave out a different paper per case, so every case is ranked against one HPOA graph
without the annotation rows citing ANY case paper of the evaluated Phenopacket-store cases (all PMIDs
in their file names and externalReferences). For one case this removes its own paper and the other
cases' papers as well. That is not a lower bound for HPOA: the other papers' rows also thin competing
diseases, which can lift the gold disease, so the 10 folds below are the closer per-case estimate.
LIRICAL and the other RareBench sets list no PMIDs in the repository; they are ranked against the same
graph, which leaves their own source papers in unless a Phenopacket-store case shares them.

A per-case LOPO is approximated by 10 folds of the case papers (cases that share a PMID stay in one fold,
seed 0, balanced by cases): fold k's Phenopacket-store cases are ranked against the graph without the rows
citing fold k's papers, so a case loses its own paper and about a tenth of the other case papers.

`prepare` writes one filtered phenotype.hpoa per variant into --hpoa-dir (deterministic, regenerated by
run_hpoa_lopo.sh before every build) and the deletion counts into deletions.json. Only rows the build
reads (not NOT, aspect P) are ever removed.

  base         the file unchanged (reproduces the stored §9.22 development ranks)
  lopo         rows citing a held-out PMID, also when they cite another source (main LOPO graph)
  lopo_strip   rows whose every reference is a held-out PMID (rows with another source stay)
  rand_s<k>    as many rows as lopo, drawn uniformly from all read rows (seed k)
  rand_dz_s0   as many rows as lopo from each HPOA disease, drawn from its rows that lopo keeps
  nopmid       rows citing any PMID (a bound for sets whose source PMIDs are unknown)
  rand_nopmid  as many rows as nopmid, drawn uniformly from all read rows
  lopo_f<k>    rows citing a paper of fold k (ranked by `rank-fold`, fold k's Phenopacket-store cases only)

`stats` compares each graph's ranks with S-mix (frozen E3 system, dev_v3llmd_ns_ot0.5.json) and with
the unfiltered HPOA graph: per set paired_stats.compare with the gold-disease cluster CI, and
paired_stats.macro_compare over the rare, the common and all nine sets. Development sets only.

    python pilot/scripts/hpoa_lopo.py prepare --hpoa-dir DIR
    python pilot/scripts/hpoa_lopo.py rank-fold --fold K [--check dev_lopo.json]
    python pilot/scripts/hpoa_lopo.py stats
"""
